-- Snowflake user creation
-- Step 1: Use an admin role
USE ROLE ACCOUNTADMIN;

-- Step 2: Create the ticketing_role and assign it to ACCOUNTADMIN
CREATE ROLE IF NOT EXISTS ticketing_role;
GRANT ROLE ticketing_role TO USER xxxxxxxxxxxx;

-- Step 3: Create a default warehouse
CREATE WAREHOUSE IF NOT EXISTS ticketing_wh WITH warehouse_size='x-small'; 
GRANT USAGE ON WAREHOUSE ticketing_wh TO ROLE ticketing_role;

-- Step 4: Create the `dbt` user and assign to the ticketing_role
CREATE USER IF NOT EXISTS dbt
  PASSWORD='xxxxxxxxxx'
  LOGIN_NAME='dbt'
  MUST_CHANGE_PASSWORD=FALSE
  DEFAULT_WAREHOUSE='TICKETING_WH'
  DEFAULT_ROLE=TICKETING_ROLE
  DEFAULT_NAMESPACE='TICKETING.RAW'
  COMMENT='DBT user used for data transformation';
ALTER USER dbt SET TYPE = LEGACY_SERVICE;
GRANT ROLE TICKETING_ROLE TO USER dbt;


-- Step 5: Create a database and schema for the Event Ticketing project
CREATE DATABASE IF NOT EXISTS TICKETING;
CREATE SCHEMA IF NOT EXISTS TICKETING.RAW;
CREATE SCHEMA IF NOT EXISTS TICKETING.STAGING;
CREATE SCHEMA IF NOT EXISTS TICKETING.MARTS;

-- Step 6: Grant permissions to the `TICKETING_ROLE` 
GRANT ALL ON WAREHOUSE TICKETING_WH TO ROLE TICKETING_ROLE;
GRANT ALL ON DATABASE TICKETING TO ROLE TICKETING_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE TICKETING TO ROLE TICKETING_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE TICKETING TO ROLE TICKETING_ROLE;
GRANT ALL ON ALL TABLES IN SCHEMA TICKETING.RAW TO ROLE TICKETING_ROLE;
GRANT ALL ON FUTURE TABLES IN SCHEMA TICKETING.RAW TO ROLE TICKETING_ROLE;


-- Set defaults
USE WAREHOUSE TICKETING_WH;
USE DATABASE TICKETING;
USE SCHEMA RAW;
